package com.kinhiro.rgkcn.mixin;

import com.kinhiro.rgkcn.util.EchoWrench;
import net.minecraft.core.dispenser.DispenseItemBehavior;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.Items;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.block.DispenserBlock;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfoReturnable;

@Mixin(DispenserBlock.class)
public abstract class MixinDispenserBlock {
    @Inject(method = "getDispenseMethod", at = @At("HEAD"), cancellable = true)
    private void rgkcn$getDispenseMethod$echoWrench(
        final Level level,
        final ItemStack itemStack,
        final CallbackInfoReturnable<DispenseItemBehavior> cir
    ) {
        if (itemStack.is(Items.ECHO_SHARD)) cir.setReturnValue(new EchoWrench.DispenseBehavior());
    }
}
